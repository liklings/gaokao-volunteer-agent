def resolve_city_province(city: str | None) -> str | None:
    """把学校实际所在城市名反查成它实际属于的省份。查不到（表里没有这个城市名，
    比如县级市、简写、或者数据本身就有误差）时返回 None——调用方应该把 None
    当成"不确定"而不是"不匹配"，不能拿一张不完整的表去硬性排除候选。
    """
    if not city:
        return None
    return CITY_TO_PROVINCE.get(city.strip())
